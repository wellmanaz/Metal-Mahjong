function finalizeLayout(list, allowFlip) {
  let t = list.map(p => ({ ...p }));
  if (t.length % 2) {                          // drop one tile nothing rests on
    const onTop = t.filter(p => !t.some(q => q.z === p.z + 1 && overlap(p, q)));
    const victim = onTop.sort((a, b) => b.z - a.z)[0];
    t.splice(t.indexOf(victim), 1);
  }
  if (allowFlip) {
    const maxX = Math.max(...t.map(p => p.x)), maxY = Math.max(...t.map(p => p.y));
    if (Math.random() < .5) t.forEach(p => p.x = maxX - p.x);
    if (Math.random() < .5) t.forEach(p => p.y = maxY - p.y);
  }
  const minX = Math.min(...t.map(p => p.x)), minY = Math.min(...t.map(p => p.y));
  t.forEach(p => { p.x -= minX; p.y -= minY; });
  return t;
}

/* Neighbour lists. A tile is covered by any tile one level up that overlaps it at all,
   and blocked on a side by any same-level tile directly beside it, including ones
   staggered half a tile up or down. */
function buildGeom(list) {
  const g = list.map((p, i) => ({ ...p, id: i, above: [], left: [], right: [] }));
  for (const a of g) for (const b of g) {
    if (a === b) continue;
    if (b.z === a.z + 1 && overlap(a, b)) a.above.push(b.id);
    if (b.z === a.z && Math.abs(b.y - a.y) < 2) {
      if (b.x === a.x - 2) a.left.push(b.id);
      if (b.x === a.x + 2) a.right.push(b.id);
    }
  }
  return g;
}
let SIDE_BLOCKING = true;   // classic rule; off = only tiles on top block
const freeWith = (t, alive) =>
  !t.above.some(i => alive.has(i)) &&
  (!SIDE_BLOCKING || !t.left.some(i => alive.has(i)) || !t.right.some(i => alive.has(i)));

function solvableAssign(geom, ids, facePairs) {
  for (let attempt = 0; attempt < 500; attempt++) {
    const alive = new Set(ids), pairs = shuffleArr(facePairs.slice()), asg = new Map();
    let idx = 0, ok = true;
    while (alive.size) {
      const free = [...alive].filter(i => freeWith(geom[i], alive));
      if (free.length < 2) { ok = false; break; }
      shuffleArr(free);
      asg.set(free[0], pairs[idx]); asg.set(free[1], pairs[idx]); idx++;
      alive.delete(free[0]); alive.delete(free[1]);
    }
    if (ok) return asg;
  }
  return null;
}

/* Deal faces by simulating a winning game with a tray of TRAY_SIZE slots
   (a full tray loses, so at most TRAY_SIZE-1 unmatched tiles may be held).
   pOpen = how often the simulated player takes a new album instead of completing
   one already in the tray. When a pair is completed, the generator prefers a
   partner that was NOT reachable when the first copy was taken, so the first copy
   has to sit in the tray. Returns Map(id -> face) or null. */
const TRAY_SIZE = 4;
function assignWithTray(geom, ids, pairFaces, initialOpen, pOpen, attempts = 400) {
  const cap = TRAY_SIZE - 1;
  if (initialOpen.length > cap) return null;
  for (let attempt = 0; attempt < attempts; attempt++) {
    const alive = new Set(ids), asg = new Map();
    const open = initialOpen.map(face => ({ face, reachable: new Set() }));
    let idx = 0, ok = true;
    while (alive.size) {
      const free = [...alive].filter(i => freeWith(geom[i], alive));
      if (!free.length) { ok = false; break; }
      const c = free[rnd(free.length)];
      const remaining = alive.size;
      const canOpen = idx < pairFaces.length && open.length < cap && remaining >= open.length + 2;
      const mustOpen = open.length === 0;
      if (mustOpen && !canOpen) { ok = false; break; }
      if (mustOpen || (canOpen && Math.random() < pOpen)) {
        open.push({ face: pairFaces[idx++], reachable: new Set(free) });
        asg.set(c, open[open.length - 1].face);
      } else {
        const hidden = open.filter(o => !o.reachable.has(c));
        const pool = hidden.length && Math.random() < .85 ? hidden : open;
        const pick = pool[rnd(pool.length)];
        asg.set(c, pick.face);
        open.splice(open.indexOf(pick), 1);
      }
      alive.delete(c);
    }
    if (ok && !open.length && idx === pairFaces.length) return asg;
  }
  return null;
}
