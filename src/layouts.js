/* ---------- Layouts ----------
   Coordinates are half-tile units: a tile at (x,y,z) covers x..x+2, y..y+2 on level z.
   Tiles may sit half a tile apart in either direction on the same level (staggered rows
   and columns), and upper-level tiles may straddle 2 or 4 tiles below. */
const rnd = n => Math.floor(Math.random() * n);
const shuffleArr = a => { for (let i = a.length - 1; i > 0; i--) { const j = rnd(i + 1); [a[i], a[j]] = [a[j], a[i]]; } return a; };

/* KMahjongg .layout format (v1.0 / v1.1). Each character is a quarter of a tile;
   '1' marks a tile's top-left corner, '2','4','3' fill the other corners. */
function parseKmahjongg(text) {
  const lines = text.split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith("#"));
  if (!/^kmahjongg-layout-v1\.[01]$/.test(lines[0] || "")) throw new Error("First line must be kmahjongg-layout-v1.0 or v1.1");
  let h = 16;
  const rows = [];
  for (const l of lines.slice(1)) {
    let m;
    if ((m = /^h(\d+)$/.exec(l))) h = +m[1];
    else if (/^[wd]\d+$/.test(l)) continue;
    else if (/^[.1234]+$/.test(l)) rows.push(l);
  }
  if (!rows.length || rows.length % h) throw new Error(`Expected levels of ${h} rows, got ${rows.length} rows`);
  const t = [];
  rows.forEach((row, i) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "1") t.push({ x, y: i % h, z: Math.floor(i / h) });
  });
  if (!t.length) throw new Error("No tiles found");
  return t;
}

/* Compact authoring format: one char per tile, '#' = tile. A row starting with '>'
   is shifted right by half a tile. Each level has its own dx/dy (half units). */
function fromRows(levels) {
  const t = [];
  levels.forEach((L, z) => {
    L.rows.forEach((r, ri) => {
      let sx = 0;
      if (r[0] === ">") { sx = 1; r = r.slice(1); }
      [...r].forEach((ch, ci) => { if (ch === "#") t.push({ x: (L.dx || 0) + sx + 2 * ci, y: (L.dy || 0) + 2 * ri, z }); });
    });
  });
  return t;
}

const overlap = (a, b) => Math.max(0, 2 - Math.abs(a.x - b.x)) * Math.max(0, 2 - Math.abs(a.y - b.y));
const support = (p, list) => list.reduce((s, q) => s + (q.z === p.z - 1 ? overlap(p, q) : 0), 0);

/* Remove tiles that aren't fully resting on the level below (repeat until stable). */
function dropUnsupported(list) {
  let t = list.slice(), changed = true;
  while (changed) {
    const keep = t.filter(p => p.z === 0 || support(p, t) === 4);
    changed = keep.length !== t.length;
    t = keep;
  }
  return t;
}

