function generatedLayout() {
  const C = 12; // board centre in half units
  const extent = list => Math.max(...list.map(p => Math.abs(p.x + 1 - C)));
  for (let tries = 0; tries < 400; tries++) {
    const L0 = [], R = 6 + rnd(3), starts = [];
    let n = 7 + rnd(5);
    for (let r = 0; r < R; r++) {
      // mostly even steps keep rows aligned; an occasional odd step staggers a row by half a tile
      if (r) n += Math.random() < .3 ? (rnd(2) ? 1 : -1) : (rnd(3) - 1) * 2;
      n = Math.max(4, Math.min(12, n));
      const start = C - n;
      starts.push(start);
      const holes = new Set();
      if (r > 0 && r < R - 1 && n >= 6 && Math.random() < .4) {
        const k = 1 + rnd(Math.floor(n / 2) - 1);
        holes.add(k); holes.add(n - 1 - k);
      }
      for (let k = 0; k < n; k++) if (!holes.has(k)) L0.push({ x: start + 2 * k, y: 2 * r, z: 0 });
    }
    if (Math.random() < .6) {                  // turtle-style wing tiles between two rows
      const r = 1 + rnd(R - 3);
      let X = Math.min(starts[r], starts[r + 1]) - 2;
      for (let i = 0, len = 1 + rnd(2); i < len; i++, X -= 2) {
        L0.push({ x: X, y: 2 * r + 1, z: 0 }, { x: 2 * C - 2 - X, y: 2 * r + 1, z: 0 });
      }
    }
    const t = L0.slice();
    let lower = L0;
    const levels = 3 + rnd(3);
    for (let z = 1; z < levels; z++) {
      const ys = lower.map(p => p.y);
      const minY = Math.min(...ys) + rnd(2), maxY = Math.max(...ys) - rnd(2);
      const limit = extent(lower) - 1 - rnd(3);  // each level pulls in from the one below
      const layer = [];
      for (let Y = minY; Y <= maxY; Y += 2) {
        const cands = [];
        for (let X = C - 1 - limit; X <= C - 1 + limit; X++) {
          const p = { x: X, y: Y, z };
          if (lower.reduce((s, q) => s + overlap(p, q), 0) === 4) cands.push(X);
        }
        cands.sort((a, b) => Math.abs(a + 1 - C) - Math.abs(b + 1 - C));
        const chosen = [], free = v => chosen.every(c => Math.abs(c - v) >= 2);
        for (const X of cands) {
          const M = 2 * C - 2 - X;
          if (!cands.includes(M)) continue;
          if (X === M) { if (free(X)) chosen.push(X); }
          else if (free(X) && free(M) && Math.abs(X - M) >= 2) chosen.push(X, M);
        }
        chosen.forEach(X => layer.push({ x: X, y: Y, z }));
      }
      if (layer.length < 2) break;
      t.push(...layer);
      lower = layer;
    }
    const levelsUsed = Math.max(...t.map(p => p.z)) + 1;
    if (t.length >= 84 && t.length <= 144 && levelsUsed >= 3) return t;
  }
  return parseKmahjongg(KMJ_TURTLE);
}

/* Random stacked board modelled on current mobile Mahjong games: a dense base
   grid (some columns dropped half a tile), then 2-3 levels whose tiles are mostly
   placed half a tile off the tiles below, so they straddle two or four of them. */
let SMALL_BOARD = false;   // phone-sized puzzle
function randomStackLayout() {
  const wrap = typeof document !== "undefined" && document.getElementById("boardWrap");
  const portrait = SMALL_BOARD || (wrap ? wrap.clientHeight > wrap.clientWidth : false);
  const [minTiles, maxTiles] = SMALL_BOARD ? [36, 64] : [96, 144];
  for (let tries = 0; tries < 300; tries++) {
    const W = SMALL_BOARD ? 4 + rnd(2) : portrait ? 6 + rnd(2) : 9 + rnd(3);
    const H = SMALL_BOARD ? 5 + rnd(2) : portrait ? 7 + rnd(3) : 5 + rnd(2);
    const sym = Math.random() < .65;
    const mirrorX = X => 2 * W - 2 - X;
    const colShift = [];
    for (let c = 0; c < W; c++) colShift[c] = sym && c >= W - 1 - c ? colShift[W - 1 - c] : (Math.random() < .22 ? 1 : 0);
    const base = [];
    const holeP = SMALL_BOARD ? .03 + Math.random() * .07 : .06 + Math.random() * .12;
    for (let c = 0; c < W; c++) for (let r = 0; r < H; r++) {
      const src = sym && c > W - 1 - c ? W - 1 - c : c;
      const key = `${src},${r}`;
      base.holes ||= {};
      if (!(key in base.holes)) base.holes[key] = Math.random() < holeP;
      if (!base.holes[key]) base.push({ x: 2 * c, y: 2 * r + colShift[c], z: 0 });
    }
    delete base.holes;
    const t = base.slice();
    let lower = base;
    const levels = SMALL_BOARD ? 3 : 3 + rnd(2);
    for (let z = 1; z < levels; z++) {
      const cands = [];
      const minY = Math.min(...base.map(p => p.y)), maxY = Math.max(...base.map(p => p.y));
      for (let X = 0; X <= 2 * W - 2; X++) for (let Y = minY; Y <= maxY; Y++) {
        const p = { x: X, y: Y, z };
        const cov = lower.reduce((s, q) => s + overlap(p, q), 0);
        if (cov < 2) continue;                 // must rest at least half on the level below
        const halfOff = lower.some(q => overlap(p, q) === 2 || overlap(p, q) === 1);
        // prefer the half-offset spots, then fully-supported ones
        cands.push({ X, Y, w: Math.random() + (halfOff ? .9 : 0) + (cov === 4 ? .3 : 0) });
      }
      cands.sort((a, b) => b.w - a.w);
      const layer = [];
      const target = Math.floor(lower.length * (.6 + Math.random() * .25));
      const clash = (X, Y) => layer.some(q => Math.abs(q.x - X) < 2 && Math.abs(q.y - Y) < 2);
      for (const { X, Y } of cands) {
        if (layer.length >= target) break;
        if (clash(X, Y)) continue;
        if (sym) {
          const M = mirrorX(X);
          if (M !== X && (Math.abs(M - X) < 2 || clash(M, Y) || !cands.some(c => c.X === M && c.Y === Y))) continue;
          layer.push({ x: X, y: Y, z });
          if (M !== X) layer.push({ x: M, y: Y, z });
        } else layer.push({ x: X, y: Y, z });
      }
      if (layer.length < 2) break;
      t.push(...layer);
      lower = layer;
    }
    if (t.length >= minTiles && t.length <= maxTiles) return t;
  }
  return generatedLayout();
}

